-- Safe, repeatable setup for the Aish Fatima public gallery.
-- This only manages policies for the new gallery_media table and gallery-media bucket.
-- It does NOT drop tables, rows, existing site media, or any other storage bucket.

insert into storage.buckets (id, name, public)
values ('gallery-media', 'gallery-media', true)
on conflict (id) do update set public = true;

create table if not exists public.gallery_media (
  id bigint generated by default as identity primary key,
  name text not null,
  storage_path text not null unique,
  public_url text not null,
  media_type text not null check (media_type in ('image','video')),
  created_at timestamptz not null default now()
);

alter table public.gallery_media enable row level security;

-- Remove policies created by earlier draft versions, including broad delete access.
drop policy if exists "Public can view gallery media" on public.gallery_media;
drop policy if exists "Signed-in client can add gallery media" on public.gallery_media;
drop policy if exists "Signed-in client can delete gallery media" on public.gallery_media;
drop policy if exists "Public can read gallery media" on public.gallery_media;
drop policy if exists "Authenticated client can add gallery media" on public.gallery_media;

drop policy if exists "Public can view gallery bucket" on storage.objects;
drop policy if exists "Signed-in client can upload gallery files" on storage.objects;
drop policy if exists "Public can read gallery media files" on storage.objects;
drop policy if exists "Authenticated client can upload gallery media files" on storage.objects;

-- Public visitors can read gallery metadata; only signed-in users can insert metadata.
create policy "Public can read gallery media" on public.gallery_media
for select to anon, authenticated using (true);

create policy "Authenticated client can add gallery media" on public.gallery_media
for insert to authenticated with check (true);

-- Public visitors can view the gallery files; signed-in users can upload.
create policy "Public can read gallery media files" on storage.objects
for select to anon, authenticated using (bucket_id = 'gallery-media');

create policy "Authenticated client can upload gallery media files" on storage.objects
for insert to authenticated with check (bucket_id = 'gallery-media');

-- No delete policy is created. Disable public sign-ups and keep only the intended client account.
